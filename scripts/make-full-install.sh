#!/usr/bin/env bash
# Makes full-install.sql: a COMPLETE fresh Agent Metra database in one file (for a new PostgreSQL, e.g. your VPS).
#   1) all tables, indexes, keys (schema of a fully migrated database, no data)
#   2) industries (wide list), packages + credit top-ups, settings (branding, bank, trial, credits)
#   3) super admin account
#   4) the 4 TEST shops (15 / 200 / 750 / 2,000 products, with brands)
#
# Usage:  SUPER_ADMIN_EMAIL=info@metrocoding.com SUPER_ADMIN_PASSWORD='...' scripts/make-full-install.sh SOURCE_DB_URL > full-install.sql
#   SOURCE_DB_URL = a database with ALL migrations applied (only its structure is copied, never its data).
# Load into an EMPTY database:  psql -h localhost -p 5433 -U agentmetra -d agentmetra -v ON_ERROR_STOP=1 -f full-install.sql
set -euo pipefail
SRC="${1:?source database url}"
HERE="$(cd "$(dirname "$0")/.." && pwd)"
EMAIL="${SUPER_ADMIN_EMAIL:?SUPER_ADMIN_EMAIL}"
PASS="${SUPER_ADMIN_PASSWORD:?SUPER_ADMIN_PASSWORD}"

cat <<'EOF'
-- Agent Metra – FULL INSTALL (generated by scripts/make-full-install.sh)
-- Run ONCE on an EMPTY database:
--   psql -h localhost -p 5433 -U agentmetra -d agentmetra -v ON_ERROR_STOP=1 -f full-install.sql
-- Then start the API: it checks the tables (startup migrations) and is ready.

-- ═════════════ 1) TABLES ═════════════
EOF
pg_dump "$SRC" --schema=public --schema-only --no-owner --no-privileges --no-comments \
  | grep -v -E '^(SET transaction_timeout|\\restrict|\\unrestrict|CREATE SCHEMA public;|COMMENT ON SCHEMA public)'

cat <<'EOF'

-- ═════════════ 2) INDUSTRIES, PACKAGES, SETTINGS ═════════════
SET search_path = public;
BEGIN;
INSERT INTO industry (name, is_active)
SELECT v.name, TRUE FROM (VALUES
  ('General'), ('Fashion and clothing'), ('Shoes and bags'), ('Jewellery and watches'), ('Baby and kids'), ('Toys and games'),
  ('Electronics'), ('Mobile phones and accessories'), ('Computers and IT'), ('Home appliances'),
  ('Home and living'), ('Furniture'), ('Hardware and building'), ('Garden and plants'),
  ('Beauty and health'), ('Cosmetics and skin care'), ('Pharmacy and medical'), ('Salon and spa'), ('Gym and fitness'),
  ('Food and drinks'), ('Grocery and supermarket'), ('Restaurant and cafe'), ('Bakery and cakes'),
  ('Books and stationery'), ('Gifts and flowers'), ('Sports and outdoor'), ('Pets'),
  ('Vehicles and parts'), ('Agriculture'), ('Printing and packaging'),
  ('Education'), ('Travel'), ('Hotels and stays'), ('Events and weddings'), ('Photography'),
  ('Real estate'), ('Insurance and finance'), ('Services'), ('Repair and maintenance'), ('Cleaning services'),
  ('Delivery and courier'), ('Software and digital'), ('Marketing and advertising'), ('Other')
) AS v(name) WHERE NOT EXISTS (SELECT 1 FROM industry i WHERE LOWER(i.name) = LOWER(v.name));

INSERT INTO platform_setting (key, value) VALUES
  ('branding', '{"name": "Agent Metra", "address": "", "by_line": "by Metrocoding", "tagline": "AI sales assistant", "website": "", "whatsapp": "", "company_name": "Metrocoding", "primary_color": "#4f46e5", "support_email": "", "support_phone": ""}'::jsonb),
  ('bank_details', '{"note": "Use your company name as the reference.", "branch": "", "bank_name": "", "account_name": "Metrocoding", "account_number": ""}'::jsonb),
  ('signup_trial', '{"days": 30, "enabled": false, "package_id": null}'::jsonb)
ON CONFLICT (key) DO NOTHING;
-- web push keys: the API makes them itself on first start.

-- credit top-ups come from the packages section below.
EOF
grep -v -E '^\s*--' "$HERE/migrations/manual/packages-2026-10-final.sql" | sed '/^\s*$/d'
echo "COMMIT;"

HASH="$(python3 - "$PASS" <<'PY'
import hashlib, os, sys
salt = os.urandom(16).hex()
key = hashlib.scrypt(sys.argv[1].encode(), salt=salt.encode(), n=16384, r=8, p=1, dklen=64, maxmem=64 * 1024 * 1024)
print(f"{salt}:{key.hex()}")
PY
)"
cat <<EOF

-- ═════════════ 3) SUPER ADMIN ═════════════
INSERT INTO app_user (name, email, password_hash, is_active, is_super_admin, team_role, email_verified_at)
VALUES ('Super Admin', '${EMAIL,,}', '$HASH', TRUE, TRUE, 'owner', NOW())
ON CONFLICT DO NOTHING;
UPDATE app_user SET is_super_admin = TRUE, is_active = TRUE WHERE LOWER(email) = '${EMAIL,,}';

-- ═════════════ 4) 4 TEST SHOPS ═════════════
EOF
python3 "$HERE/scripts/make-test-shops.py" 2>/dev/null
echo
echo "-- ═════════════ check ═════════════"
echo "-- SELECT count(*) FROM industry; SELECT code, name FROM platform_package ORDER BY sort_order; SELECT email FROM app_user WHERE is_super_admin;"
